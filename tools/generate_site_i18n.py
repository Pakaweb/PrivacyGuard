def load_rest() -> dict[str, dict[str, str]]:
    merged: dict[str, dict[str, str]] = {}
    from generate_site_i18n_rest import REST
    from generate_site_i18n_more import MORE
    from generate_site_i18n_east import EAST
    merged.update(REST)
    merged.update(MORE)
    merged.update(EAST)
    return merged


def main() -> None:
    tables = {"en-US": EN, "pt-BR": PT}
    rest_path = Path(__file__).with_name("generate_site_i18n_rest.py")
    if rest_path.exists():
        tables.update(load_rest())
    missing = []
    for code, table in tables.items():
        for key in EN:
            if key not in table:
                missing.append(f"{code}:{key}")
    if missing:
        raise SystemExit("Missing keys:\n" + "\n".join(missing[:40]))

    out = Path(__file__).resolve().parents[1] / "website" / "i18n.js"
    payload = (
        "window.PG_SITE_LANGS = "
        + json.dumps(LANGS, ensure_ascii=False)
        + ";\nwindow.PG_SITE_FLAGS = "
        + json.dumps(FLAGS, ensure_ascii=False)
        + ";\nwindow.PG_SITE_I18N = "
        + json.dumps(tables, ensure_ascii=False)
        + ";\n"
    )
    out.write_text(payload, encoding="utf-8")
    print(f"Wrote {out} ({out.stat().st_size} bytes)")


if __name__ == "__main__":
    main()
