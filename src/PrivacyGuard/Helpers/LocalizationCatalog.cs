    public static string Get(string languageCode, string key)
    {
        var table = TableFor(Normalize(languageCode));
        if (table.TryGetValue(key, out var value) && !string.IsNullOrEmpty(value))
        {
            return value;
        }

        return En.GetValueOrDefault(key, key);
    }

    public static string Normalize(string? languageCode)
    {
        if (string.IsNullOrWhiteSpace(languageCode))
        {
            return AppPreferences.DefaultLanguage;
        }

        if (languageCode.Equals("ar", StringComparison.OrdinalIgnoreCase)
            || languageCode.StartsWith("ar-", StringComparison.OrdinalIgnoreCase))
        {
            return "ar";
        }

        foreach (var option in Languages)
        {
            if (option.Code.Equals(languageCode, StringComparison.OrdinalIgnoreCase))
            {
                return option.Code;
            }
        }

        var prefix = languageCode.Split('-')[0];
        var family = Languages.FirstOrDefault(option =>
            option.Code.StartsWith(prefix + "-", StringComparison.OrdinalIgnoreCase));
        return family?.Code ?? AppPreferences.DefaultLanguage;
    }

